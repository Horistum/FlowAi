package org.flowlang.targets.builtin

import org.flowlang.generators.manifest.TargetProjectionIdentityChecks
import org.flowlang.generators.manifest.TargetInput
import org.flowlang.generators.manifest.TargetJob
import org.flowlang.generators.manifest.TargetManifest
import org.flowlang.generators.manifest.TargetManifestRenderer
import org.flowlang.generators.manifest.TargetRenderMode
import org.flowlang.generators.manifest.TargetRenderPolicy
import org.flowlang.generators.manifest.TargetRendererContractValidator
import org.flowlang.generators.manifest.TargetRendererPayload
import org.flowlang.generators.manifest.TargetReviewArtifactRenderer
import org.flowlang.generators.manifest.TargetStep

class JenkinsManifestRenderer : TargetManifestRenderer {
    override val target: String = "jenkins"
    override val artifactFileName: String = "Jenkinsfile"

    override fun render(manifest: TargetManifest): String {
        TargetRendererContractValidator.requireRenderable(manifest, target)
        TargetRenderingIdentityChecks.requireValid(manifest, { it }, { it }, JenkinsConditionSecrets.names(manifest))
        manifest.jobs.forEach { job ->
            val imageIds = job.steps.flatMap { it.flatten() }.filter {
                val payload = it.rendererPayload
                payload?.kind == JenkinsProjectionPayloadKinds.JENKINS_STEP && payload.reference == "docker-build"
            }.map { it.id }
            TargetProjectionIdentityChecks.requireNames(
                "render.jobs.${job.id}.image-variables", imageIds, JenkinsImageBuildProjectionValues::jenkinsVariable)
            val loopItems = job.steps.flatMap { it.flatten() }.filter { it.type == "loop" }
                .mapNotNull { it.params["item"] }.toSet()
            require(imageIds.none { JenkinsImageBuildProjectionValues.jenkinsVariable(it) in loopItems }) {
                "Jenkins loop items cannot capture renderer-owned image result variables."
            }
        }
        val readiness = TargetRenderPolicy.requireSafe(manifest)
        if (readiness.mode == TargetRenderMode.REVIEW_ONLY) return TargetReviewArtifactRenderer.render(manifest, readiness)
        check(readiness.mode == TargetRenderMode.EXECUTABLE)

        val sb = StringBuilder()
        sb.appendLine("// Generated by Flow standard ${manifest.standardVersion}")
        sb.appendLine("// Target: ${manifest.target}; compatibility: ${manifest.compatibility.status}")
        sb.appendLine("// Projection model: typed bindings; raw command execution is not emitted.")
        manifest.mappingNotes.forEach { note ->
            sb.appendLine("// Flow mapping note [${note.level}] ${note.feature} ${note.nodeId}: ${note.message.replace("\n", " ")}")
        }
        sb.appendLine("pipeline {")
        sb.appendLine("  agent any")
        sb.appendLine("  options { timestamps() }")
        renderJenkinsParameters(manifest, sb)
        renderJenkinsTriggers(manifest, sb)
        renderJenkinsOpaqueEnvironment(manifest, sb)
        sb.appendLine("  stages {")
        manifest.jobs.forEach { job -> renderJenkinsJob(job, manifest, sb) }
        sb.appendLine("  }")
        sb.appendLine("}")
        return sb.toString()
    }

    private fun renderJenkinsParameters(manifest: TargetManifest, sb: StringBuilder) {
        if (manifest.inputs.isEmpty()) return
        sb.appendLine("  parameters {")
        manifest.inputs.forEach { input ->
            when (input.type) {
                "boolean" -> sb.appendLine("    booleanParam(name: '${groovyEscape(input.name)}', defaultValue: ${input.defaultValue?.toBooleanStrictOrNull() ?: false})")
                "option" -> sb.appendLine("    choice(name: '${groovyEscape(input.name)}', choices: [${input.choices.joinToString(", ") { groovyString(it) }}])")
                else -> sb.appendLine("    string(name: '${groovyEscape(input.name)}', defaultValue: ${groovyString(input.defaultValue ?: "")})")
            }
        }
        sb.appendLine("  }")
    }

    private fun renderJenkinsTriggers(manifest: TargetManifest, sb: StringBuilder) {
        val schedules = manifest.triggers.filter { it.type == "SCHEDULE" }
        if (schedules.isEmpty()) return
        sb.appendLine("  triggers {")
        schedules.forEach { trigger ->
            require(trigger.scheduleKind == "CRON") { "Executable Jenkins schedule '${trigger.id}' must be CRON." }
            val expression = requireNotNull(trigger.scheduleExpression) {
                "Jenkins schedule '${trigger.id}' is missing expression."
            }
            sb.appendLine("    cron(${groovyString(expression)})")
        }
        sb.appendLine("  }")
    }

    private fun renderJenkinsOpaqueEnvironment(manifest: TargetManifest, sb: StringBuilder) {
        val opaqueNames = JenkinsConditionSecrets.names(manifest)
        if (opaqueNames.isEmpty()) return
        sb.appendLine("  environment {")
        opaqueNames.forEach { name ->
            sb.appendLine("    ${safeEnvName(name)} = credentials('${groovyEscape(name)}')")
        }
        sb.appendLine("  }")
    }

    private fun renderJenkinsJob(job: TargetJob, manifest: TargetManifest, sb: StringBuilder) {
        sb.appendLine("    stage(${groovyString(job.name)}) {")
        sb.appendLine("      steps {")
        sb.appendLine("        script {")
        if (job.steps.isEmpty()) {
            sb.appendLine("          error(${groovyString("Flow job '${job.id}' has no materialized target steps.")})")
        } else {
            val bindings = JenkinsConditionValueScope.requireBound(job.steps, manifest.inputs.map { it.name }.toSet())
            job.steps.forEach { step -> renderJenkinsStep(step, manifest, sb, "          ", bindings) }
        }
        sb.appendLine("        }")
        sb.appendLine("      }")
        sb.appendLine("    }")
    }

    private fun renderJenkinsStep(
        step: TargetStep,
        manifest: TargetManifest,
        sb: StringBuilder,
        indent: String,
        bindings: JenkinsConditionValueScope.Bindings,
        branchScopedApproval: Boolean = false
    ) {
        step.mappingNotes.forEach { note ->
            sb.appendLine("${indent}// Flow mapping note [${note.level}] ${note.feature} ${note.nodeId}: ${note.message.replace("\n", " ")}")
        }
        TargetProjectionDiagnostics.append(JenkinsProjectionSyntax, step, manifest.inputs, sb, indent, "//")
        when (step.type) {
            "try" -> renderJenkinsTry(step, manifest, sb, indent, bindings)
            "try-body", "error-handler", "parallel-branch" ->
                step.children.forEach { renderJenkinsStep(it, manifest, sb, indent, bindings) }
            "parallel" -> renderJenkinsParallel(step, manifest, sb, indent, bindings)
            "condition" -> renderJenkinsCondition(step, manifest, sb, indent, bindings)
            "retry" -> renderJenkinsRetry(step, manifest, sb, indent, bindings)
            "loop" -> renderJenkinsLoop(step, manifest, sb, indent, bindings)
            "match" -> renderJenkinsMatch(step, manifest, sb, indent, bindings)
            "approval" -> renderJenkinsApproval(step, sb, indent, branchScopedApproval)
            else -> renderJenkinsLeaf(step, manifest, sb, indent)
        }
        bindings.producers[step.id]?.let { sb.appendLine("${indent}def $it = true") }
    }

    private fun renderJenkinsParallel(step: TargetStep, manifest: TargetManifest, sb: StringBuilder, indent: String, bindings: JenkinsConditionValueScope.Bindings) {
        requireJenkinsStructure(step, "approval-parallel")
        require(manifest.jobs.flatMap { it.steps }.contains(step)) {
            "Jenkins parallel nesting requires separate topology evidence."
        }
        require(step.metadata["failFast"] in setOf("false", "true") && step.children.isNotEmpty()) {
            "Jenkins parallel requires nonempty branch membership and a boolean failFast policy."
        }
        step.children.forEach { JenkinsParallelProjectionScope.requireBranch(it) }
        sb.appendLine("${indent}parallel([")
        step.children.forEach { branch ->
            // Labels and approval messages are data, never branch identities.
            sb.appendLine("${indent}  ${groovyString(branch.id)}: {")
            var workspaceOpen = false
            for (child in branch.children) {
                val workspace = JenkinsParallelProjectionScope.usesWorkspace(child)
                if (workspaceOpen && !workspace) sb.appendLine("${indent}    }")
                if (!workspaceOpen && workspace)
                    sb.appendLine("${indent}    dir(${groovyString(".flow-parallel/${branch.id}")}) {")
                renderJenkinsStep(child, manifest, sb, if (workspace) "$indent      " else "$indent    ", bindings, branchScopedApproval = true)
                workspaceOpen = workspace
            }
            if (workspaceOpen) sb.appendLine("${indent}    }")
            sb.appendLine("${indent}  },")
        }
        sb.appendLine("${indent}  failFast: ${step.metadata.getValue("failFast")}")
        sb.appendLine("${indent}])")
    }

    private fun renderJenkinsApproval(step: TargetStep, sb: StringBuilder, indent: String, branchScoped: Boolean = false) {
        val payload = requireNotNull(step.rendererPayload) {
            "Executable Jenkins approval '${step.id}' has no provider renderer payload."
        }
        require(payload.kind == JenkinsProjectionPayloadKinds.JENKINS_STEP && payload.reference == "input") {
            "Jenkins approval '${step.id}' requires the owned JENKINS_STEP/input payload, not '${payload.kind}/${payload.reference}'."
        }
        val mode = requireNotNull(payload.bindings["mode"]?.value) {
            "Jenkins approval '${step.id}' is missing resolved mode binding."
        }
        require(mode == "manual") {
            "Jenkins approval '${step.id}' cannot render unsupported mode '$mode'."
        }
        val message = requireNotNull(payload.bindings["message"]?.value) {
            "Jenkins approval '${step.id}' is missing resolved message binding."
        }
        // InputStep otherwise hashes the message into its HTTP routing ID. Parallel messages may repeat.
        // The fixed prefix also prevents InputStep's first-character capitalization from merging identities.
        val identity = if (branchScoped) ", id: ${groovyString("Flow_${step.id}")}" else ""
        sb.appendLine("${indent}input message: ${groovyString(message)}$identity")
    }

    private fun renderJenkinsTry(
        step: TargetStep,
        manifest: TargetManifest,
        sb: StringBuilder,
        indent: String,
        bindings: JenkinsConditionValueScope.Bindings
    ) {
        requireJenkinsStructure(step, "try-catch")
        val body = step.children.firstOrNull { it.type == "try-body" }
        val handler = step.children.firstOrNull { it.type == "error-handler" }
        val workflowFailure = step.metadata["workflowFailurePolicy"] == "true"
        val disposition = step.metadata["workflowFailureDisposition"]
        val errorBinding = step.metadata["workflowFailureErrorBinding"]
        if (workflowFailure) {
            require(disposition in setOf("PROPAGATE", "RECOVER")) {
                "Jenkins workflow failure boundary '${step.id}' has invalid disposition '$disposition'."
            }
            require(errorBinding != null && JENKINS_IDENTIFIER.matches(errorBinding)) {
                "Jenkins workflow failure boundary '${step.id}' has invalid error binding '$errorBinding'."
            }
        }
        sb.appendLine("${indent}try {")
        body?.children.orEmpty().forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        sb.appendLine("${indent}} catch (flowError) {")
        if (workflowFailure) {
            sb.appendLine("${indent}  def $errorBinding = flowError")
        }
        handler?.children.orEmpty().forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        if (workflowFailure && disposition == "PROPAGATE") {
            sb.appendLine("${indent}  throw flowError")
        }
        sb.appendLine("${indent}}")
    }

    private fun renderJenkinsCondition(
        step: TargetStep,
        manifest: TargetManifest,
        sb: StringBuilder,
        indent: String,
        bindings: JenkinsConditionValueScope.Bindings
    ) {
        requireJenkinsStructure(step, "if")
        val condition = step.params["condition"] ?: "false"
        val values = bindings.conditions[step.id].orEmpty()
        val translated = JenkinsTargetExpressionTranslator.groovy(
            condition, manifest.inputs, manifest.compatibility.expressionSupport, values)
        // Keep established artifact bytes for the direct binding case while all expressions use
        // the same AST renderer. Parentheses supplied by the if statement preserve precedence.
        val rendered = if (values.isEmpty()) translated else translated.removeSurrounding("(", ")")
        sb.appendLine("${indent}if ($rendered) {")
        step.children.forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        sb.appendLine("${indent}}")
    }

    private val JENKINS_IDENTIFIER = Regex("[A-Za-z_][A-Za-z0-9_]*")

    private fun renderJenkinsRetry(step: TargetStep, manifest: TargetManifest, sb: StringBuilder, indent: String, bindings: JenkinsConditionValueScope.Bindings) {
        requireJenkinsStructure(step, "retry")
        require(JenkinsRetryProjectionScope.supportsRenderedBody(step.children, manifest.inputs.map { it.name }.toSet())) {
            "Jenkins retry requires sequential tasks, conditions, literal matches, finite loops and fixed zero-delay retries; other control mappings need explicit replay evidence."
        }
        require(step.params.keys == setOf("max", "delay", "backoff")) { "Jenkins retry requires the complete authored policy." }
        val max = requireNotNull(step.params["max"]?.toIntOrNull()) { "Jenkins retry requires an integer total attempt limit." }
        require(JenkinsRetryProjectionScope.supports(max, step.params.getValue("delay"), step.params.getValue("backoff"))) {
            "Jenkins retry supports only a positive total attempt limit with fixed zero delay."
        }
        sb.appendLine("${indent}retry($max) {")
        step.children.forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        sb.appendLine("${indent}}")
    }

    private fun renderJenkinsLoop(step: TargetStep, manifest: TargetManifest, sb: StringBuilder, indent: String, bindings: JenkinsConditionValueScope.Bindings) {
        requireJenkinsStructure(step, "for-in")
        require(step.params.keys == setOf("item", "source")) { "Jenkins loop requires exactly its authored item and source." }
        val item = step.params.getValue("item")
        require(JenkinsLoopProjectionScope.safeItem(item) && manifest.inputs.none { it.name == item }) {
            "Jenkins loop item '$item' conflicts with the native execution scope."
        }
        val items = requireNotNull(JenkinsLoopProjectionScope.literalItems(step.params.getValue("source"))) {
            "Jenkins loop supports only an authored string-literal list."
        }
        require(JenkinsLoopProjectionScope.supportsRenderedBody(step.children, manifest.inputs.map { it.name }.toSet() + item)) {
            "Jenkins loop requires sequential tasks, conditions, literal matches, fixed zero-delay retries and finite nested loops with distinct lexical item bindings."
        }
        sb.appendLine("${indent}for (def $item in ${items.joinToString(", ", "[", "]") { groovyString(it) }}) {")
        step.children.forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        sb.appendLine("${indent}}")
    }

    private fun renderJenkinsMatch(step: TargetStep, manifest: TargetManifest, sb: StringBuilder, indent: String, bindings: JenkinsConditionValueScope.Bindings) {
        requireJenkinsStructure(step, "literal-match")
        val cases = step.children.filter { it.type == "match-case" }
        require(JenkinsMatchProjectionScope.supportsRenderedMatch(step, manifest.inputs.map { it.name }.toSet())) {
            "Jenkins match requires exclusive literal cases, an empty error branch and sequential tasks, conditions, fixed zero-delay retries, finite loops or nested matches."
        }
        // The source is an inert literal; no implicit result is introduced into the native scope.
        cases.forEachIndexed { index, branch ->
            val guard = JenkinsTargetExpressionTranslator.groovy(branch.params.getValue("condition"),
                manifest.inputs, manifest.compatibility.expressionSupport)
            sb.appendLine("$indent${if (index == 0) "if" else "} else if"} ($guard) {")
            branch.children.forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        }
        sb.appendLine("${indent}} else {")
        step.children.single { it.type == "match-default" }.children.forEach { renderJenkinsStep(it, manifest, sb, "$indent  ", bindings) }
        sb.appendLine("${indent}}")
    }

    private fun requireJenkinsStructure(step: TargetStep, reference: String) {
        val payload = requireNotNull(step.rendererPayload) {
            "Executable Jenkins structural step '${step.id}' has no provider renderer payload."
        }
        require(
            payload.kind == JenkinsProjectionPayloadKinds.JENKINS_STRUCTURE &&
                payload.reference == reference
        ) {
            "Jenkins structural step '${step.id}' requires the owned ${JenkinsProjectionPayloadKinds.JENKINS_STRUCTURE}/$reference payload, not '${payload.kind}/${payload.reference}'."
        }
    }

    private fun renderJenkinsLeaf(
        step: TargetStep,
        manifest: TargetManifest,
        sb: StringBuilder,
        indent: String
    ) {
        val opaqueNames = TargetProjectionDiagnostics.opaqueNames(step)
        if (opaqueNames.isNotEmpty()) {
            val items = opaqueNames.joinToString(", ") {
                JenkinsProjectionSyntax.mappingSpec(it)
            }
            sb.appendLine("${indent}${JenkinsProjectionSyntax.boundary()}([$items]) {")
            renderJenkinsLeafBody(step, manifest, sb, "$indent  ")
            sb.appendLine("${indent}}")
        } else {
            renderJenkinsLeafBody(step, manifest, sb, indent)
        }
    }

    private fun renderJenkinsLeafBody(
        step: TargetStep,
        manifest: TargetManifest,
        sb: StringBuilder,
        indent: String
    ) {
        val payload = requireNotNull(step.rendererPayload) {
            "Executable Jenkins step '${step.id}' has no renderer payload."
        }
        require(payload.kind == JenkinsProjectionPayloadKinds.JENKINS_STEP) {
            "Jenkins cannot render payload kind '${payload.kind}' for step '${step.id}'."
        }
        when (payload.reference) {
            "git" -> {
                val context = "Jenkins git payload for '${step.id}'"
                val urlBinding = requireNotNull(payload.bindings["url"]) { "$context requires url binding." }
                val branchBinding = requireNotNull(payload.bindings["branch"]) { "$context requires branch binding." }
                val urlValue = CheckoutProjectionValues.gitUrl(payload, "url", context)
                val branchValue = CheckoutProjectionValues.branch(payload, "branch", context)
                val depth = payload.bindings["depth"]?.let {
                    CheckoutProjectionValues.depth(payload, "depth", context)
                } ?: 0
                require(urlBinding.value != null && branchBinding.value != null)
                val url = groovyString(urlValue)
                val branch = groovyString(branchValue)
                if (depth == 0 && !Regex("[0-9a-fA-F]{40}").matches(branchValue)) {
                    sb.appendLine("${indent}git branch: $branch, url: $url")
                } else {
                    sb.appendLine("${indent}checkout scmGit(")
                    sb.appendLine("${indent}  branches: [[name: $branch]],")
                    if (depth > 0) sb.appendLine("${indent}  extensions: [cloneOption(depth: $depth, noTags: false, shallow: true)],")
                    sb.appendLine("${indent}  userRemoteConfigs: [[url: $url]]")
                    sb.appendLine("${indent})")
                }
            }
            "docker-build" -> renderDockerBuild(step.id, payload, manifest, sb, indent)
            else -> error("Unsupported Jenkins structured payload reference '${payload.reference}' for step '${step.id}'.")
        }
    }

    private fun renderDockerBuild(
        stepId: String,
        payload: TargetRendererPayload,
        manifest: TargetManifest,
        sb: StringBuilder,
        indent: String
    ) {
        val context = "Jenkins Docker build payload for '$stepId'"
        val image = ImageBuildProjectionValues.image(payload, "image", context)
        val buildContext = ImageBuildProjectionValues.requireLiteralWorkspacePath(
            ImageBuildProjectionValues.buildContext(payload, "context", context),
            "$context binding 'context'"
        )
        val dockerfile = ImageBuildProjectionValues.dockerfile(payload, "dockerfile", context)?.let {
            ImageBuildProjectionValues.requireLiteralWorkspacePath(it, "$context binding 'dockerfile'")
        }
        require(ImageBuildProjectionValues.isDefaultDockerfile(buildContext, dockerfile)) {
            "$context cannot render custom Dockerfile '$dockerfile' without falling back to Docker CLI argument strings."
        }
        val push = ImageBuildProjectionValues.push(payload, "push", context)
        val imageArgument = JenkinsImageBuildProjectionValues.jenkinsImageArgument(
            image,
            manifest.inputs,
            "$context binding 'image'"
        )
        val variable = JenkinsImageBuildProjectionValues.jenkinsVariable(stepId)
        val buildCall = if (buildContext == ".") {
            "docker.build($imageArgument)"
        } else {
            "docker.build($imageArgument, ${groovyString(buildContext)})"
        }
        sb.appendLine("${indent}def $variable = $buildCall")
        if (push) sb.appendLine("${indent}$variable.push()")
    }
}
